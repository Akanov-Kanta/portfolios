import { createRequire } from "node:module";
const require = createRequire("/Users/nazarakanov/development/dossier/package.json");
const { chromium } = require("playwright");
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto(`http://localhost:${process.env.PORT ?? 3240}/`, { waitUntil: "networkidle" });
const s = await page.evaluate(() => { const el = document.getElementById("dossier"); return el.parentElement.getBoundingClientRect().top + scrollY; });
await page.evaluate((y) => scrollTo(0, y), Math.round(s + 2.5 * 900));
await page.waitForTimeout(1200);
const info = await page.evaluate(() => [...document.querySelectorAll("[data-strip]")].map((e) => [e.tagName, e.getAttribute("href"), getComputedStyle(e).visibility]));
console.log(JSON.stringify(info));
const link = page.locator('[data-strip="2"]');
await link.focus();
console.log("focused:", await page.evaluate(() => document.activeElement?.getAttribute("aria-label")));
await page.screenshot({ path: "/Users/nazarakanov/development/dossier/reference/shots/round2/desktop-dossier-2-focus.png" });
const [popup] = await Promise.all([ctx.waitForEvent("page", { timeout: 5000 }).catch(() => null), link.click()]);
console.log("new tab:", popup ? popup.url() : "none");
await browser.close();
